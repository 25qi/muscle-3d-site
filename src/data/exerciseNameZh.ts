export function exerciseNameZh(name: string): string {
  const toks = name
    .toLowerCase()
    .replace(/[()]/g, ' ')
    .replace(/[-/]/g, ' ')
    .replace(/[.]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)

  const out: string[] = []
  let i = 0
  while (i < toks.length) {
    let matched = false
    for (const [phrase, zh] of PHRASES) {
      if (
        i + phrase.length <= toks.length &&
        phrase.every((p, k) => toks[i + k] === p)
      ) {
        out.push(zh)
        i += phrase.length
        matched = true
        break
      }
    }
    if (matched) continue
    const w = toks[i]
    const singular = w.endsWith('s') ? w.slice(0, -1) : null
    if (WORDS[w]) out.push(WORDS[w])
    else if (singular && WORDS[singular]) out.push(WORDS[singular]) // 複數 → 用單數翻譯
    else if (SKIP.has(w) || (singular && SKIP.has(singular))) {
      /* 略過 */
    } else if (/^\d+$/.test(w)) {
      /* 純數字略過 */
    } else out.push(` ${w} `) // 無法翻譯 → 保留英文並加空格,避免跟中文黏在一起
    i++
  }

  const zh = out.join('').replace(/\s+/g, ' ').trim()
  return zh || name
}
